/** 동전이 두 종류(a, b)일 때 최소 개수를 직접 세어 본다. 만들 수 없으면 -1. */
function twoCoinAnswer(a: number, b: number, k: number): number {
  let best = -1;
  for (let y = 0; y * b <= k; y++) {
    const rest = k - y * b;
    if (rest % a === 0) {
      const total = rest / a + y;
      if (best === -1 || total < best) best = total;
    }
  }
  return best;
}

