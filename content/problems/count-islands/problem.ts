/** cell(r, c)가 true인 칸을 땅(1)으로 하는 N x M 지도 */
function makeMap(n: number, m: number, cell: (r: number, c: number) => boolean): string {
  const rows: string[] = [];
  for (let r = 0; r < n; r++) {
    let row = "";
    for (let c = 0; c < m; c++) row += cell(r, c) ? "1" : "0";
    rows.push(row);
  }
  return `${n} ${m}\n${rows.join("\n")}\n`;
}

/**
 * 하나로 길게 이어진 뱀 모양 섬. 짝수 번째 줄(0부터)은 모두 땅이고,
 * 홀수 번째 줄은 오른쪽 끝과 왼쪽 끝에 번갈아 땅이 한 칸씩 있다.
 */
function snake(r: number, c: number, m: number): boolean {
  if (r % 2 === 0) return true;
  return r % 4 === 1 ? c === m - 1 : c === 0;
}

